"""
Step 3 — Per-Cell-Line Motif Grouping, Filtering, and Representative Selection

Usage: python 03_cell_pipeline.py <BSSID>
Run via the sbatch scripts generated by 02_generate_jobs.py.

For a single cell line this script:
  1. Runs TOMTOM to compare the cell line's IC-filtered motifs against themselves.
     This identifies groups of similar motifs within the same cell line.
  2. Runs TOMTOM to compare the cell line's motifs against the JASPAR database.
     This annotates motifs with known transcription factor identities.
  3. Clusters similar motifs using network distance (Dijkstra path length on the
     TOMTOM similarity graph).  All pairwise distances within a cluster must be
     <= GROUP_DIST_THRESHOLD so that every member is "close" to every other member.
  4. Filters clusters: keeps only those where at least one JASPAR-matched TF is
     expressed above EXPR_THRESHOLD in this cell line (log10 scale).
  5. Merges clusters that share at least one JASPAR annotation, because shared
     JASPAR identity implies they represent the same TF family.
  6. Selects one representative PWM per cluster (the motif nearest the group's
     component-wise median in Pearson distance).
  7. Writes the representative motifs to the cell line's output MEME file.

Output: results/cell_motifs/{bssid}/{bssid}_cell_motifs.meme

Intermediate TOMTOM outputs are kept in the same directory for inspection:
  results/cell_motifs/{bssid}/{bssid}_self_tomtom.txt
  results/cell_motifs/{bssid}/{bssid}_jaspar_tomtom.txt
"""

import os
import sys
import subprocess
import numpy as np
from collections import defaultdict

# The data root: the work directory you created with bin/setup_work_dir.py and unpacked the
# GitHub and Zenodo data into. `source env.sh` exports it, or set it yourself (see PATHS.md).
ENHANCER_ROOT = os.environ.get("ENHANCER_ROOT")
if not ENHANCER_ROOT:
    raise SystemExit("set ENHANCER_ROOT to your work directory: source env.sh (see PATHS.md)")

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, SCRIPT_DIR)

from utils import (
    parse_meme_file, write_meme_file, read_tomtom,
    group_by_network, normalize_orientations, representative_motif,
)

# ── configuration ─────────────────────────────────────────────────────────────
OUTPUT_DIR     = os.path.join(SCRIPT_DIR, "results", "cell_motifs")
JASPAR_MEME    = ENHANCER_ROOT + "/JASPAR2022_CORE_vertebrates_non_redundant_unique_names.meme"
GENE_NAME_FILE = ENHANCER_ROOT + "/gene_ENSG_name.txt"
TF_INFO_FILE   = ENHANCER_ROOT + "/motif_analysis/TF_Information.txt"
EXPR_DIR       = ENHANCER_ROOT + "/training_y"

# TOMTOM run settings (permissive threshold; Python filtering is applied separately)
TOMTOM_MIN_OVERLAP = 7
TOMTOM_E_THRESH    = 1

# Thresholds applied when loading TOMTOM results
SELF_E_VALUE  = 0.01   # within-cell grouping (strict: only very similar motifs merge)
SELF_P_VALUE  = 0.01
JASPAR_E_VALUE = 0.05  # JASPAR annotation (relaxed: catch weaker TF similarities)
JASPAR_P_VALUE = 0.01

GROUP_DIST_THRESHOLD = 0.01   # max Dijkstra distance for two motifs to be co-clustered
EXPR_THRESHOLD       = 0.5    # minimum log10 expression to consider a TF "expressed"


# ── TOMTOM runner ─────────────────────────────────────────────────────────────

def run_tomtom(query_meme, target_meme, output_file):
    """
    Run TOMTOM in text mode, redirecting stdout to output_file.
    Raises subprocess.CalledProcessError on non-zero exit.
    """
    cmd = [
        "tomtom", "-no-ssc", "-verbosity", "2", "-text",
        "-dist", "pearson",
        "-min-overlap", str(TOMTOM_MIN_OVERLAP),
        "-evalue", "-thresh", str(TOMTOM_E_THRESH),
        query_meme, target_meme,
    ]
    if os.path.exists(output_file) and os.path.getsize(output_file) > 0:
        print(f"[03] using the existing TOMTOM table {output_file} (delete it to recompute; a self-TOMTOM of 7,500 PWMs takes hours)", flush=True); return
    with open(output_file, "w") as fh:
        subprocess.run(cmd, stdout=fh, check=True)


# ── Gene and TF mapping loaders ───────────────────────────────────────────────

def load_gene_mappings():
    """
    Parse gene_ENSG_name.txt and return (idx→ENSG, ENSG→idx) dicts.
    Only lines with at least two tab-separated fields are counted; the first
    field is the Ensembl gene ID.
    """
    idx_to_ensg = {}
    idx = 0
    with open(GENE_NAME_FILE) as fh:
        for line in fh:
            fields = line.strip().split("\t")
            if len(fields) >= 2:
                idx_to_ensg[idx] = fields[0]
                idx += 1
    ensg_to_idx = {v: k for k, v in idx_to_ensg.items()}
    return idx_to_ensg, ensg_to_idx


def load_tf_motif_mapping(ensg_set):
    """
    Build a dict from JASPAR TF name (uppercase) → Ensembl gene ID using
    TF_Information.txt.  Only human TFs present in our gene expression dataset
    are included.  If the same TF name appears multiple times, the first
    occurrence wins.
    """
    motif_to_gene = {}
    with open(TF_INFO_FILE) as fh:
        header   = fh.readline().strip().split("\t")
        col_tf   = header.index("TF_Name")
        col_db   = header.index("DBID")
        col_sp   = header.index("TF_Species")
        for line in fh:
            fields = line.strip().split("\t")
            if len(fields) <= max(col_tf, col_db, col_sp):
                continue
            if fields[col_sp] != "Homo_sapiens":
                continue
            tf_name = fields[col_tf].upper()
            ensg    = fields[col_db]
            if ensg in ensg_set and tf_name not in motif_to_gene:
                motif_to_gene[tf_name] = ensg
    return motif_to_gene


# ── Filtering and merging ─────────────────────────────────────────────────────

def filter_by_jaspar_expression(group_to_motifs, motif_to_jaspar,
                                motif_to_gene, ensg_to_idx, gene_exp):
    """
    Retain only groups where at least one JASPAR-matched TF has expression
    above EXPR_THRESHOLD in this cell line.

    Returns:
      filtered_groups : dict {group_id: [motif_ids]}
      group_jaspar    : dict {group_id: {jaspar_base_name: expression_value}}
    """
    filtered_groups = {}
    group_jaspar    = {}

    for gid, motif_ids in group_to_motifs.items():
        jaspar_expr = {}
        for mid in motif_ids:
            for jaspar_name in motif_to_jaspar.get(mid, []):
                # JASPAR names can have version suffixes (e.g. "MA0001_1"); strip them
                base = jaspar_name.rsplit("_", 1)[0].upper()
                ensg = motif_to_gene.get(base)
                if not ensg:
                    continue
                idx  = ensg_to_idx.get(ensg)
                if idx is None:
                    continue
                expr = float(gene_exp[idx])
                if expr > EXPR_THRESHOLD:
                    jaspar_expr[base] = expr

        if jaspar_expr:
            filtered_groups[gid] = motif_ids
            group_jaspar[gid]    = jaspar_expr

    return filtered_groups, group_jaspar


def merge_by_shared_jaspar(group_to_motifs, group_jaspar):
    """
    Iteratively merge groups that share at least one JASPAR annotation.
    Shared JASPAR identity indicates the groups represent the same TF, so
    combining them reduces redundancy.

    Returns new dicts with sequential integer keys starting from 0.
    """
    merged_motifs = {}
    merged_jaspar = {}
    processed     = set()
    new_id        = 0

    for gid, jaspar_dict in group_jaspar.items():
        if gid in processed:
            continue
        to_merge   = {gid}
        union_jasp = set(jaspar_dict)
        processed.add(gid)

        # Expand: find all groups that share any JASPAR name with the growing union
        changed = True
        while changed:
            changed = False
            for other, other_jasp in group_jaspar.items():
                if other in processed:
                    continue
                if union_jasp & set(other_jasp):
                    to_merge.add(other)
                    union_jasp |= set(other_jasp)
                    processed.add(other)
                    changed = True

        combined_motifs = sorted({mid for g in to_merge for mid in group_to_motifs.get(g, [])})
        combined_jaspar = {k: v for g in to_merge for k, v in group_jaspar.get(g, {}).items()}

        if combined_motifs and combined_jaspar:
            merged_motifs[new_id] = combined_motifs
            merged_jaspar[new_id] = combined_jaspar
            new_id += 1

    return merged_motifs, merged_jaspar


# ── Main ──────────────────────────────────────────────────────────────────────

def main(bssid):
    cell_dir = os.path.join(OUTPUT_DIR, bssid)
    os.makedirs(cell_dir, exist_ok=True)

    icfiltered_meme = os.path.join(cell_dir, f"{bssid}_ICfiltered.meme")
    self_tomtom_out = os.path.join(cell_dir, f"{bssid}_self_tomtom.txt")
    jasp_tomtom_out = os.path.join(cell_dir, f"{bssid}_jaspar_tomtom.txt")
    cell_meme_out   = os.path.join(cell_dir, f"{bssid}_cell_motifs.meme")

    if not os.path.exists(icfiltered_meme):
        sys.exit(f"ERROR: {icfiltered_meme} not found — run 01_ic_filter.py first.")

    # ── 1. Run TOMTOM ─────────────────────────────────────────────────────────
    print(f"[03] {bssid}: running self-tomtom …")
    run_tomtom(icfiltered_meme, icfiltered_meme, self_tomtom_out)

    print(f"[03] {bssid}: running JASPAR-tomtom …")
    run_tomtom(icfiltered_meme, JASPAR_MEME, jasp_tomtom_out)

    # ── 2. Load motifs and parse TOMTOM results ────────────────────────────────
    motifs, motif_names = parse_meme_file(icfiltered_meme)
    # Motif names are global integer IDs written as strings; convert for dict lookup
    name_to_idx = {int(n): i for i, n in enumerate(motif_names)}

    self_tomtom = read_tomtom(self_tomtom_out, SELF_E_VALUE, SELF_P_VALUE)
    self_tomtom["Query_ID"]  = self_tomtom["Query_ID"].astype(int)
    self_tomtom["Target_ID"] = self_tomtom["Target_ID"].astype(int)

    jasp_tomtom = read_tomtom(jasp_tomtom_out, JASPAR_E_VALUE, JASPAR_P_VALUE)
    jasp_tomtom["Query_ID"] = jasp_tomtom["Query_ID"].astype(int)

    # ── 3. Build motif → JASPAR annotation map ────────────────────────────────
    motif_to_jaspar = defaultdict(list)
    for _, row in jasp_tomtom.iterrows():
        motif_to_jaspar[row["Query_ID"]].append(row["Target_ID"])
    # Deduplicate JASPAR hits per motif
    motif_to_jaspar = {k: list(set(v)) for k, v in motif_to_jaspar.items()}

    print(f"[03] {bssid}: {len(motif_to_jaspar)} motifs have JASPAR annotations")

    # ── 4. Cluster similar motifs via network distance ─────────────────────────
    print(f"[03] {bssid}: clustering the similarity graph (all-pairs shortest paths; 1-3 h for ~7,500 motifs) ...", flush=True)
    groups         = group_by_network(self_tomtom, GROUP_DIST_THRESHOLD)
    group_to_motifs = {i: grp for i, grp in enumerate(groups)}

    # ── 5. Load gene expression and filter groups by TF expression ─────────────
    _, ensg_to_idx = load_gene_mappings()
    motif_to_gene  = load_tf_motif_mapping(set(ensg_to_idx))
    gene_exp = np.load(os.path.join(EXPR_DIR, f"{bssid}.y.npy"), allow_pickle=True)
    gene_exp = gene_exp / np.log2(10)   # convert from log2 to log10 scale

    group_to_motifs, group_jaspar = filter_by_jaspar_expression(
        group_to_motifs, motif_to_jaspar, motif_to_gene, ensg_to_idx, gene_exp
    )
    print(f"[03] {bssid}: {len(group_to_motifs)} groups after JASPAR expression filter")

    # ── 6. Merge groups that share a JASPAR annotation ─────────────────────────
    group_to_motifs, group_jaspar = merge_by_shared_jaspar(group_to_motifs, group_jaspar)
    print(f"[03] {bssid}: {len(group_to_motifs)} groups after merging by shared JASPAR")

    # ── 7. Select one representative PWM per group ────────────────────────────
    # All motifs come from the same CNN architecture so they share the same
    # filter length — normalize_orientations and representative_motif require this.
    rep_motifs, rep_names = [], []
    for gid, motif_ids in group_to_motifs.items():
        pwms = [motifs[name_to_idx[mid]] for mid in motif_ids if mid in name_to_idx]
        if not pwms:
            continue
        pwms = normalize_orientations(pwms)
        rep_motifs.append(representative_motif(pwms))
        rep_names.append(gid)

    write_meme_file(rep_motifs, cell_meme_out, rep_names)
    print(f"[03] {bssid}: {len(rep_motifs)} representative motifs → {cell_meme_out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("Usage: python 03_cell_pipeline.py <BSSID>")
    main(sys.argv[1])
